const LANGUAGE_STORAGE_KEY = "carlos-franca-portfolio-language";

function getPreferredLanguage() {
  try {
    const savedLanguage = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return savedLanguage === "en" || savedLanguage === "pt" ? savedLanguage : "pt";
  } catch (error) {
    return "pt";
  }
}

function translate(key, language) {
  return translations[language][key] || translations.pt[key] || key;
}

function applyTranslations(language) {
  const selectedLanguage = language === "en" ? "en" : "pt";
  document.documentElement.lang = selectedLanguage === "en" ? "en" : "pt-BR";
  document.documentElement.dataset.language = selectedLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = translate(element.dataset.i18n, selectedLanguage);
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.alt = translate(element.dataset.i18nAlt, selectedLanguage);
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", translate(element.dataset.i18nAriaLabel, selectedLanguage));
  });

  document.querySelectorAll("button[data-language]").forEach((button) => {
    const isSelected = button.dataset.language === selectedLanguage;
    button.classList.toggle("is-active", isSelected);
    button.setAttribute("aria-pressed", String(isSelected));
  });
}

function setLanguage(language) {
  const selectedLanguage = language === "en" ? "en" : "pt";
  applyTranslations(selectedLanguage);
  try {
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, selectedLanguage);
  } catch (error) {
    // Translation still works when storage is unavailable.
  }
}

function prefersReducedMotion() {
  return window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches;
}

function closeMobileMenu() {
  const menu = document.querySelector("#mobile-menu");
  const toggle = document.querySelector("[data-menu-toggle]");
  if (!menu || !toggle) return;
  menu.hidden = true;
  toggle.setAttribute("aria-expanded", "false");
  document.body.classList.remove("menu-open");
}

function setupLanguageControls() {
  document.querySelectorAll("button[data-language]").forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.dataset.language));
  });
}

function setupMobileMenu() {
  const menu = document.querySelector("#mobile-menu");
  const toggle = document.querySelector("[data-menu-toggle]");
  if (!menu || !toggle) return;
  toggle.addEventListener("click", () => {
    const isOpen = toggle.getAttribute("aria-expanded") === "true";
    menu.hidden = isOpen;
    toggle.setAttribute("aria-expanded", String(!isOpen));
    document.body.classList.toggle("menu-open", !isOpen);
  });
  document.querySelectorAll("#mobile-menu a").forEach((link) => link.addEventListener("click", closeMobileMenu));
}

function setupAnchorNavigation() {
  document.querySelectorAll('a[href^="#"]').forEach((link) => {
    const targetId = link.getAttribute("href");
    const target = document.querySelector(targetId);
    if (!target) return;
    link.addEventListener("click", (event) => {
      event.preventDefault();
      target.scrollIntoView({ behavior: prefersReducedMotion() ? "auto" : "smooth", block: "start" });
      if (targetId !== "#hero") history.replaceState(null, "", targetId);
      closeMobileMenu();
    });
  });
}

function setActiveSection(sectionId) {
  document.querySelectorAll("[data-section-link]").forEach((link) => {
    link.classList.toggle("is-active", link.dataset.sectionLink === sectionId);
  });
}

function setupSectionObserver() {
  const sections = Array.from(document.querySelectorAll("[data-section]"));
  if (!sections.length) return;
  if ("IntersectionObserver" in window) {
    const observer = new IntersectionObserver((entries) => {
      entries.filter((entry) => entry.isIntersecting).forEach((entry) => setActiveSection(entry.target.id));
    }, { rootMargin: "-35% 0px -55%", threshold: 0 });
    sections.forEach((section) => observer.observe(section));
    return;
  }
  const updateFromScroll = () => {
    const current = sections.reduce((visibleSection, section) => {
      return section.getBoundingClientRect().top <= window.innerHeight * 0.4 ? section : visibleSection;
    }, sections[0]);
    setActiveSection(current.id);
  };
  window.addEventListener("scroll", updateFromScroll, { passive: true });
  updateFromScroll();
}

function setupGridParallax() {
  const grid = document.querySelector(".grid-layer");
  if (!grid || prefersReducedMotion()) return;
  let frame = 0;
  const update = () => {
    frame = 0;
    const shift = Math.max(-72, Math.min(72, window.scrollY * -0.08));
    document.documentElement.style.setProperty("--grid-shift", `${shift.toFixed(2)}px`);
  };
  const requestUpdate = () => {
    if (!frame) frame = window.requestAnimationFrame(update);
  };
  window.addEventListener("scroll", requestUpdate, { passive: true });
  update();
}

function initSite() {
  applyTranslations(getPreferredLanguage());
  setupLanguageControls();
  setupMobileMenu();
  setupAnchorNavigation();
  setupSectionObserver();
  setupGridParallax();
}

window.siteTranslations = translations;
window.getPreferredLanguage = getPreferredLanguage;
window.setLanguage = setLanguage;
window.applyTranslations = applyTranslations;
window.initSite = initSite;

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initSite, { once: true });
} else {
  initSite();
}
